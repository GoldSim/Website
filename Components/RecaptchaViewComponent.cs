using GoldSim.Web.Models.Components;

namespace GoldSim.Web.Components {

  /*============================================================================================================================
  | CLASS: RECAPTCHA VIEW COMPONENT
  \---------------------------------------------------------------------------------------------------------------------------*/
  /// <summary>
  ///   Defines a <see cref="ViewComponent"/> which renders a script for embedding a reCAPTCHA component onto the page.
  /// </summary>
  public sealed class RecaptchaViewComponent : ViewComponent {

    /*==========================================================================================================================
    | PRIVATE VARIABLES
    \-------------------------------------------------------------------------------------------------------------------------*/
    private readonly            string                          _siteKey;

    /*==========================================================================================================================
    | CONSTRUCTOR
    \-------------------------------------------------------------------------------------------------------------------------*/
    /// <summary>
    ///   Initializes a new instance of a ReCaptchaViewComponent with necessary dependencies.
    /// </summary>
    internal RecaptchaViewComponent(string siteKey) {
      _siteKey                  = siteKey;
    }

    /*==========================================================================================================================
    | METHOD: INVOKE
    \-------------------------------------------------------------------------------------------------------------------------*/
    /// <summary>
    ///   Renders a database.
    /// </summary>
    public IViewComponentResult Invoke(string action) {

      /*------------------------------------------------------------------------------------------------------------------------
      | Establish view model
      \-----------------------------------------------------------------------------------------------------------------------*/
      var viewModel             = new RecaptchaViewModel {
        SiteKey                 = _siteKey,
        Action                  = action
      };

      /*------------------------------------------------------------------------------------------------------------------------
      | Return view
      \-----------------------------------------------------------------------------------------------------------------------*/
      return View(viewModel);

    }

  } //Class
} //Namespace